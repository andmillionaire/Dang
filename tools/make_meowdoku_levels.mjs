#!/usr/bin/env node
// Pre-generates the Mewdoku puzzles: 100 arcade levels plus a pool for the in-game mini-game.
// Every puzzle has exactly one solution and is solvable by logic alone.
//   node tools/make_meowdoku_levels.mjs   (writes js/arcade/meowdoku-levels.js)
import fs from 'node:fs';
import { generate } from '../js/meowdoku-engine.js';
import { seeded } from '../js/sudoku.js';

const BANDS = [[5, 10], [6, 15], [7, 20], [8, 25], [9, 20], [10, 10]]; // [size, levels]
// [regions, solution, lockedRow]: each level starts with the cat in lockedRow already placed.
const pick = seeded(0x10c4);
const enc = p => [p.regions.map(g => String.fromCharCode(97 + g)).join(''), p.solution.join(''), (pick() * p.N) | 0];

let seed = 1;
const make = (N, count) => {
  const out = [];
  while (out.length < count) {
    const p = generate(N, seeded(0x6d3 + N * 10007 + seed++));
    if (p) out.push(p);
  }
  return out;
};

const levels = [];
for (const [N, n] of BANDS) {
  // Generate extra, then pick an evenly spread, rising run by number of deduction rounds.
  const cands = make(N, n * 3).sort((a, b) => a.steps - b.steps);
  for (let k = 0; k < n; k++) levels.push(cands[Math.round((k * (cands.length - 1)) / Math.max(1, n - 1))]);
  process.stdout.write(`${N}x${N} `);
}
const pool = [...make(5, 30), ...make(6, 30)];

const file = `// Generated by tools/make_meowdoku_levels.mjs. Do not edit by hand.
// Each entry is [regions, solution, lockedRow]: regions has one letter per cell (row by row),
// solution has the cat's column for each row, lockedRow is the row whose cat starts placed.
export const LEVELS = ${JSON.stringify(levels.map(enc))};
export const POOL = ${JSON.stringify(pool.map(enc))};
`;
fs.writeFileSync(new URL('../js/arcade/meowdoku-levels.js', import.meta.url), file);
console.log(`\nwrote ${levels.length} levels and ${pool.length} pool puzzles`);
